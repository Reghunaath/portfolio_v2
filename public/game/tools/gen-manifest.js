#!/usr/bin/env node
/* gen-manifest.js — scans a folder of PNGs and writes asset-manifest.js for
   asset-viewer.html to browse. Re-run after buying the full pack and
   dropping its files in, so the viewer picks up the new content.
   Usage: node tools/gen-manifest.js [rootDir] [--out=tools/asset-manifest.js] */
"use strict";
const fs = require("fs");
const path = require("path");

const rawArgs = process.argv.slice(2);
const rootArg = rawArgs.find(function (a) { return !a.startsWith("--"); });
const outArg = rawArgs.find(function (a) { return a.startsWith("--out="); });

const toolsDir = __dirname;
const root = path.resolve(toolsDir, rootArg || "../assets");
const outFile = outArg
  ? path.resolve(process.cwd(), outArg.slice("--out=".length))
  : path.join(toolsDir, "asset-manifest.js");

function pngSize(file) {
  const fd = fs.openSync(file, "r");
  const buf = Buffer.alloc(24);
  fs.readSync(fd, buf, 0, 24, 0);
  fs.closeSync(fd);
  const sig = Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]);
  if (!buf.slice(0, 8).equals(sig)) return null;
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

if (!fs.existsSync(root)) {
  console.error("root folder not found: " + root);
  process.exit(1);
}

const entries = [];
(function walk(dir) {
  fs.readdirSync(dir, { withFileTypes: true }).forEach(function (ent) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) { walk(full); return; }
    if (!/\.png$/i.test(ent.name)) return;
    const dims = pngSize(full);
    if (!dims) return;
    entries.push({
      path: path.relative(toolsDir, full).split(path.sep).join("/"),
      folder: path.relative(root, dir).split(path.sep).join("/") || ".",
      name: ent.name,
      width: dims.width,
      height: dims.height,
    });
  });
})(root);

entries.sort(function (a, b) { return a.path.localeCompare(b.path); });

const js =
  "/* generated by tools/gen-manifest.js — rerun after adding/replacing pack files */\n" +
  "window.ASSET_MANIFEST = " + JSON.stringify(entries, null, 2) + ";\n";
fs.writeFileSync(outFile, js);
console.error("wrote " + path.relative(process.cwd(), outFile) + " (" + entries.length + " files)");
